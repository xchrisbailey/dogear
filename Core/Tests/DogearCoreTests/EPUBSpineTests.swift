import DogearCore
import Foundation
import Testing

/// Mapping between a CFI's spine step and the EPUB resource it names. The fixture's spine has a
/// `linear="no"` item before Chapter Two, which Readium leaves out of its reading order.
struct EPUBSpineTests {
    func spine() async throws -> EPUBSpine {
        let book = try #require(Bundle.module.url(forResource: "lighthouse-ledger", withExtension: nil, subdirectory: "Fixtures"))
        return try #require(await EPUBSpine.load { entry in try? Data(contentsOf: book.appending(path: entry)) })
    }

    @Test func spineStepOfAWebReaderCFINamesItsResource() async throws {
        let spine = try await spine()

        // Generated by foliate's epubcfi.js on the fixture.
        #expect(spine.href(of: "epubcfi(/6/8[itemref-ch2]!/4[chapter-two]/82/1:24)") == "OEBPS/text/chapter-2.xhtml")
        // Range CFIs, as the web reader stores them, and the non-linear item itself.
        #expect(spine.href(of: "epubcfi(/6/6!/4[chapter-one],/4/1:0,/8/1:12)") == "OEBPS/text/chapter-1.xhtml")
        #expect(spine.href(of: "epubcfi(/6/4!/4[notes]/2/1:0)") == "OEBPS/text/notes.xhtml")
        #expect(spine.href(of: "epubcfi(/6/40!/4/2/1:0)") == nil)
        #expect(spine.href(of: "OEBPS/text/chapter-2.xhtml") == nil)
    }

    @Test func spineStepForAResourceCountsEveryItemref() async throws {
        let spine = try await spine()

        // The same prefix foliate builds with CFI.fromElements over the OPF's itemrefs.
        #expect(spine.step(of: "OEBPS/text/cover.xhtml") == "/6/2")
        #expect(spine.step(of: "OEBPS/text/chapter-2.xhtml") == "/6/8[itemref-ch2]")
        #expect(spine.step(of: "OEBPS/text/chapter-3.xhtml#ignored") == "/6/10")
        #expect(spine.step(of: "OEBPS/nav.xhtml") == nil)
    }

    @Test func missingPackageDocumentGivesNoSpine() async {
        #expect(await EPUBSpine.load { _ in nil } == nil)
    }
}
